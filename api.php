<?php
include 'db.php';
header('Content-Type: application/json');
$action = $_GET['action'] ?? '';

if ($action == 'get_bins') {
    $res = $conn->query("SELECT * FROM bins ORDER BY FIELD(priority, 'HIGH', 'MEDIUM', 'LOW', 'PENDING')");
    $bins = []; while($row = $res->fetch_assoc()) $bins[] = $row;
    echo json_encode($bins); exit();
}

if ($action == 'update_weight') {
    $id = $_POST['id']; $w = $_POST['weight'];
    $max = $conn->query("SELECT max_capacity FROM bins WHERE id=$id")->fetch_assoc()['max_capacity'];
    $p = 'PENDING';
    if(($w/$max)*100 > 80) $p = 'HIGH'; elseif(($w/$max)*100 >= 50) $p = 'MEDIUM'; elseif($w > 0) $p = 'LOW';
    $conn->query("UPDATE bins SET current_weight=$w, priority='$p' WHERE id=$id");
    echo json_encode(["status" => "success"]); exit();
}

if ($action == 'generate_route') {
    $conn->query("DELETE FROM routes");
    $conn->query("UPDATE bins SET status='PENDING'");
    $v = $conn->query("SELECT * FROM vehicles LIMIT 1")->fetch_assoc();
    
    $bins = $conn->query("SELECT * FROM bins WHERE current_weight > 0");
    $str = "";
    while($row = $bins->fetch_assoc()) {
        $pVal = 3; if($row['priority']=='HIGH') $pVal=1; elseif($row['priority']=='MEDIUM') $pVal=2;
        $str .= "{$row['id']},{$row['current_weight']},$pVal,{$row['latitude']},{$row['longitude']};";
    }

    // --- JAVA CALL ---
    $javaPath = '"C:\Program Files\Java\jdk-26.0.2\bin\java.exe"'; // Unga Java path inga check pannunga
    $classPath = "C:\\xampp\\htdocs\\smartcity\\route_engine";
    $cmd = "cd $classPath && $javaPath DijkstraRouter \"$str\" 2>&1";
    $out = trim(shell_exec($cmd));
    $ids = array_filter(explode(",", $out));

    $conn->query("INSERT INTO routes (vehicle_id) VALUES ({$v['id']})");
    $rid = $conn->insert_id; $order = 1; $load = 0;
    foreach($ids as $bid) {
        $b = $conn->query("SELECT current_weight FROM bins WHERE id=$bid")->fetch_assoc();
        if($b) {
            $conn->query("INSERT INTO route_stops (route_id, bin_id, stop_order) VALUES ($rid, $bid, $order)");
            $load += $b['current_weight']; $order++;
        }
    }
    echo json_encode(["status" => "success", "msg" => "Route Generated by Java! Load: $load kg"]); exit();
}

if ($action == 'get_driver_route') {
    $res = $conn->query("SELECT rs.id as stop_id, rs.stop_order, b.id as bin_id, b.location_name, b.latitude, b.longitude, b.current_weight 
                         FROM route_stops rs JOIN bins b ON rs.bin_id = b.id WHERE rs.status='PENDING' ORDER BY rs.stop_order ASC");
    $stops = []; while($row = $res->fetch_assoc()) $stops[] = $row;
    echo json_encode($stops); exit();
}

if ($action == 'collect') {
    $sid = $_POST['stop_id']; 
    $bid = $_POST['bin_id']; 
    $img = $_POST['image'];
    
    // Photo-a save pandrom
    $imgName = "proof_".time().".png";
    file_put_contents("uploads/".$imgName, base64_decode(preg_replace('#^data:image/\w+;base64,#i', '', $img)));
    
    $conn->query("UPDATE route_stops SET status='COMPLETED', proof_image='$imgName' WHERE id=$sid");
    $conn->query("UPDATE bins SET current_weight=0, priority='PENDING', status='COLLECTED' WHERE id=$bid");
    echo json_encode(["status" => "success"]); exit();
}
if ($action == 'submit_complaint') {
    $driverId = $_POST['driver_id'];
    $msg = $_POST['message'];
    $conn->query("INSERT INTO complaints (driver_id, message) VALUES ('$driverId', '$msg')");
    echo json_encode(["status" => "success"]); 
    exit();
}
// Admin: Complaint Resolve Panna (Photo upload kooda)
if ($action == 'resolve_complaint') {
    $id = $_POST['id'];
    $img = $_POST['image']; // Base64 image
    
    $imgName = "resolve_".time().".png";
    // Image-a uploads folder-la save pandrom
    file_put_contents("uploads/".$imgName, base64_decode(preg_replace('#^data:image/\w+;base64,#i', '', $img)));
    
    $conn->query("UPDATE complaints SET status='RESOLVED', proof_image='$imgName' WHERE id=$id");
    echo json_encode(["status" => "success"]); 
    exit();
}
?>